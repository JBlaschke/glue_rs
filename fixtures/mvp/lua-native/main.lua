local native, origin = require("module")
assert(origin:find("app/module.so", 1, true))
assert(require("module") == native)
assert(native.answer() == 42 and native.threads())
assert(native.constructors == 1)
assert(native.callback(function() return 77 end) == 77)
local ok, message = pcall(native.fail)
assert(not ok and message:find("native protected function error", 1, true))
ok, message = pcall(native.callback, function() error("native callback error") end)
assert(not ok and message:find("native callback error", 1, true))
local explicit = package.loadlib("app/module.so", "luaopen_module")
assert(explicit("module", origin).constructors == 1)
local missing, diagnostic, category = package.loadlib("app/module.so", "luaopen_absent")
assert(missing == nil and type(diagnostic) == "string" and category == "init")
ok, message = pcall(require, "failed")
assert(not ok and message:find("native protected initializer error", 1, true))
ok, message = pcall(require, "missing")
assert(not ok and message:find("luaopen_missing", 1, true))
ok, message = pcall(require, "mismatched")
assert(not ok and message:find("version mismatch", 1, true))
print(_VERSION .. " native module/secondary/TLS/callback/errors passed")
