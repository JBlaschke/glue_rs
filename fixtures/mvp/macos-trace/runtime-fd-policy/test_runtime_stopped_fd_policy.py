def physical(rows):
    # The frozen independent stopped fixture's physical record encoder is reused
    # with an extended literal probe inventory. No production formatter is used.
    with patch.object(stopped_vectors, 'IDS', IDS):
        return stopped_vectors.physical(rows)


def call(name, args=(), result=0, *, errno=0, tid=NEW):
    words = (U64, U64, U64, errno, errno) if errno else (result, result, 0, 0, 0)
    return [stopped_vectors.spec(2, name, tid, tuple(args) + (0,) * (8-len(args))),
            stopped_vectors.spec(3, name, tid, words)]


