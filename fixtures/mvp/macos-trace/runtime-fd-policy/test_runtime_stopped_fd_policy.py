def differential_errors(factory, evidence):
    result=[]
    for case in ('errors','contract','late-record','late-iterator'):
        lines=old.physical(old.stream(old.call('open',(0x7000,0,0),5)))
        kwargs={}
        if case=='errors':kwargs['errors']=b'provider loss'
        elif case=='contract':kwargs['contract_bytes']=b'{}'
        elif case=='late-record':lines[-1]=b'{bad}\n'
        else:
            original_lines=lines
            def broken():
                yield from original_lines[:-1]
                raise RuntimeError('original late iterator failure')
            lines=broken()
        try:
            factory(old.recipe_vectors.recipe._IMAGES.expected_images_program(TARGET),
                old.INVENTORY,kwargs.get('errors',b''),lines,owner_pid=OWNER,target_pid=TARGET,
                contract_bytes=kwargs.get('contract_bytes',old.base.CONTRACT),launch_evidence=evidence)
        except Exception as error:
            result.append((case,type(error).__name__,str(error)))
        else:raise AssertionError('old refusal unexpectedly returned a prefix')
    return tuple(result)


