class StoppedFdPolicyControls(unittest.TestCase):
    def no_authority(self, result):
        self.assertEqual(result.output_exemptions, ())
        for name in ('native_admission','output_capabilities_authorized','state_feed_eligible',
            'successful_effect_linearization','full_trace_acceptance','final_state_is_live',
            'retention_before_continue_proved','ofd_identity_proved','descriptor_generation_proved',
            'backing_identity_proved','native_origin_authenticated','authorizes_sink_exemptions',
            'raw_origin_authenticated','quiescence_proved','full_flags_proved',
            'c_and_trace_clock_origins_calibrated','foreign_controller_excluded'):
            self.assertIs(getattr(result, name), False, name)
        for s in result.final_bindings:
            self.assertFalse(s.kernel_generation_attested or s.output_authorized)
            self.assertNotEqual(s.state, 'ready-output')

    def accounted(self, result):
        self.assertEqual([r.ordinal for r in result.phase_accounting],
                         [p.ordinal for p in result.source.phases])
        self.assertEqual(len({r.ordinal for r in result.phase_accounting}), len(result.source.phases))
        self.assertEqual([a.entry.ordinal for a in result.attempts],
            [p.ordinal for p in result.source.phases if p.raw_scalars[0] in (2,15)
             and p.raw_scalars[2] == TARGET])
        for i,a in enumerate(result.attempts):
            row = result.phase_accounting[a.entry.ordinal-1]
            self.assertEqual(row.child_attempt_index, i)
            self.assertIsNone(row.owner_control_index)
            self.assertEqual(a.entry.raw_scalars[2], TARGET)
        for original,row in zip(result.diagnostic.phase_accounting,result.phase_accounting):
            self.assertEqual(row.reader_role,original.role)
            self.assertEqual(row.owner_control_index,original.control_index)
            if original.control_index is not None:self.assertIsNone(row.child_attempt_index)
        self.no_authority(result)

    def request_only(self, result):
        self.assertEqual(result.status, 'incomplete')
        self.assertEqual((result.windows,result.conflicts,result.transitions,result.final_bindings), ((),(),(),()))
        for a in result.attempts:
            self.assertIsNone(a.returned)
            self.assertIsNone(a.outcome)
            self.assertIsNone(a.image_epoch)
            self.assertIsNone(a.thread_instance)
        self.assertTrue(all(c.operation is None for c in result.fcntl_attempts))
        self.accounted(result)

